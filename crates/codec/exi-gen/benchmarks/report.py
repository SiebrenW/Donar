#!/usr/bin/env python3
"""Turns build/results.tsv (RESULT and MISMATCH lines of the harnesses), the size binaries and the
corpus into the tables of RESULTS.md."""
import collections, pathlib, re, subprocess, sys

build = pathlib.Path(sys.argv[1])
corpus = pathlib.Path(sys.argv[2])
LIBS = [("exi-rs", "this crate (Rust)"), ("openv2g", "OpenV2G (C)"), ("cbv2g", "libcbv2g (C)"), ("exificient", "EXIficient (Java)")]
GROUPS = [("din", "DIN SPEC 70121"), ("iso2", "ISO 15118-2:2013"), ("iso20", "ISO 15118-20")]

rows = collections.defaultdict(list)  # (lib, group) -> [(ok, total, dec, enc, mem)]
mismatch = collections.defaultdict(set)  # (lib, group) -> {(name, why)}
for line in (build / "results.tsv").read_text().splitlines():
    f = line.split("\t")
    if f[0] == "RESULT":
        rows[(f[1], f[2])].append((int(f[3]), int(f[4]), float(f[5]), float(f[6]), int(f[7])))
    elif f[0] == "MISMATCH":
        mismatch[(f[1], f[2])].add((f[3], f[4]))
env = dict(l.split("\t", 1) for l in (build / "env.tsv").read_text().splitlines())

def best(lib, group):
    r = rows.get((lib, group))
    if not r:
        return None
    return (r[0][0], r[0][1], min(x[2] for x in r), min(x[3] for x in r), r[0][4])

docs = collections.Counter()
sizes = collections.defaultdict(list)
for line in corpus.read_text().splitlines():
    n, g, h, _ = line.split("\t")
    docs[g] += 1
    sizes[g].append(len(h) // 2)

def section_bytes(path):
    """Code and constant data of a binary: __text, __const, __cstring, literals (macOS) or .text, .rodata (Linux)."""
    out = subprocess.run(["size", "-m", str(path)], capture_output=True, text=True).stdout
    total = 0
    if "Segment" in out:
        for m in re.finditer(r"Section (__text|__const|__cstring|__literal\d+|__stubs|__stub_helper): (\d+)", out):
            total += int(m.group(2))
        return total
    out = subprocess.run(["size", "-A", str(path)], capture_output=True, text=True).stdout
    for m in re.finditer(r"^(\.text|\.rodata)\s+(\d+)", out, re.M):
        total += int(m.group(2))
    return total

def table(header, body, text=False):
    w = ["| " + " | ".join(header) + " |", "|" + "|".join("---" if i == 0 or text else "---:" for i in range(len(header))) + "|"]
    for r in body:
        w.append("| " + " | ".join(str(c) for c in r) + " |")
    return "\n".join(w)

o = []
o.append("# EXI codec comparison\n")
o.append("Generated by `run.sh`; do not edit. What is measured and how: [README.md](README.md).\n")
o.append("## Setup\n")
o.append(table(["", ""], [[k, v] for k, v in env.items()], text=True))
o.append("\n## Corpus\n")
o.append("The reference documents of `cargo xtask vectors` (EXIficient's output for the XML inputs in `crates/xtask/vectors`): every document is decoded and encoded again by every library.\n")
o.append(table(["group", "documents", "smallest", "median", "largest"], [[n, docs[g], f"{min(sizes[g])} B", f"{sorted(sizes[g])[len(sizes[g]) // 2]} B", f"{max(sizes[g])} B"] for g, n in GROUPS]))

o.append("\n## Does it round-trip?\n")
o.append("A document counts when the library decodes it and encodes the result to exactly the bytes it was given. OpenV2G has no ISO 15118-20.\n")
body = []
for lib, name in LIBS:
    r = [name]
    for g, _ in GROUPS:
        b = best(lib, g)
        r.append("n/a" if b is None else f"{b[0]} / {b[1]}")
    body.append(r)
o.append(table(["library"] + [n for _, n in GROUPS], body))
fails = []
for lib, name in LIBS:
    for g, gn in GROUPS:
        for n, why in sorted(mismatch.get((lib, g), ())):
            fails.append([name, gn, f"`{n}`", why])
if fails:
    o.append("\nThe documents that did not:\n")
    o.append(table(["library", "group", "document", "what happened"], fails, text=True))

o.append("\n## Speed\n")
o.append("Nanoseconds per document, the mean over the documents that round-tripped, the fastest of several runs. Decoding builds the library's own representation (a C struct, a Rust value in an arena, a list of SAX events); encoding writes it back from that. Parsing XML and building the message by hand are not included. Documents are small (see above), so a call is dominated by fixed costs.\n")
for what, idx in (("Decode", 2), ("Encode", 3)):
    o.append(f"\n### {what} (ns per document)\n")
    body = []
    for lib, name in LIBS:
        r = [name]
        for g, _ in GROUPS:
            b = best(lib, g)
            r.append("n/a" if b is None or b[0] == 0 else f"{b[idx]:,.0f}")
        body.append(r)
    o.append(table(["library"] + [n for _, n in GROUPS], body))
o.append("\n### Documents per second, decode and encode together\n")
body = []
for lib, name in LIBS:
    r = [name]
    for g, _ in GROUPS:
        b = best(lib, g)
        r.append("n/a" if b is None or b[0] == 0 else f"{1e9 / (b[2] + b[3]):,.0f}")
    body.append(r)
o.append(table(["library"] + [n for _, n in GROUPS], body))

o.append("\n## Memory\n")
o.append("What a decoded message takes. The C libraries decode into a struct that has room for the largest message of the schema: its size is paid for every document (for ISO 15118-20 the largest of the three schemas' structs). This crate decodes into an arena the caller provides and needs what the document needs: the most any document of the corpus used. Java: the garbage collector's business, not measured.\n")
body = []
for lib, name, what in (("exi-rs", LIBS[0][1], "arena, largest document"), ("openv2g", LIBS[1][1], "document struct"), ("cbv2g", LIBS[2][1], "document struct")):
    r2 = [name, what]
    for g, _ in GROUPS:
        b = best(lib, g)
        r2.append("n/a" if b is None or b[0] == 0 else f"{b[4]:,} B")
    body.append(r2)
o.append(table(["library", "", "DIN SPEC 70121", "ISO 15118-2", "ISO 15118-20"], body))

o.append("\n## Code size\n")
o.append("Code and constant data a round trip of one protocol pulls in: a harness per protocol, built for size (`-Os` / `opt-level = \"s\"` with LTO, unused code removed by the linker) minus the same harness with no protocol. Bytes; ISO 15118-20 is the common, DC and AC schemas; ISO 15118-2 in OpenV2G includes the XML signature types.\n")
base = {}
for lib, d in (("exi-rs", "rust-size-none/release/exi-bench"), ("openv2g", "size-openv2g-none"), ("cbv2g", "size-cbv2g-none")):
    p = build / d
    base[lib] = section_bytes(p) if p.exists() else None
body = []
for lib, name in LIBS[:3]:
    r = [name]
    for g, _ in GROUPS:
        p = build / (f"rust-size-{g}/release/exi-bench" if lib == "exi-rs" else f"size-{lib}-{g}")
        if not p.exists() or base[lib] is None:
            r.append("n/a")
        else:
            r.append(f"{section_bytes(p) - base[lib]:,}")
    body.append(r)
o.append(table(["library", "DIN SPEC 70121", "ISO 15118-2", "ISO 15118-20"], body))
print("\n".join(o))
