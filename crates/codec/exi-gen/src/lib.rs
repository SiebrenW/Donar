pub const GROUPS: &[&Group] = &[&ISO20, &APP_PROTOCOL, &DIN70121, &ISO2];

pub fn group(name: &str) -> Result<&'static Group, String> {
    GROUPS.iter().copied().find(|g| g.name == name).ok_or_else(|| format!("unknown group {name}"))
}

/// Writes `<module>.rs` for each module and a `mod.rs` into `out_dir`.
pub fn generate(group: &Group, schema_dir: &Path, out_dir: &Path) -> Result<(), String> {
    let world = World::load(schema_dir, group.files)?;
    let mut model = model::Model::new(&world, group.modules)?;
    std::fs::create_dir_all(out_dir).map_err(|e| e.to_string())?;
    let mut modrs = String::from("// @generated by exi-gen; do not edit.\n");
    for (ns, module) in group.modules {
        let mut em = emit::Emitter::new(&mut model, ns);
        if let Some((dns, droot)) = group.document {
            em.document = Some((dns.to_string(), droot.to_string()));
            em.grammar_ns = group.modules.iter().map(|(n, _)| n.to_string()).collect();
        }
        em.value_table = group.value_table;
        let code = em.emit_module()?;
        std::fs::write(out_dir.join(format!("{module}.rs")), code).map_err(|e| e.to_string())?;
        modrs.push_str(&format!("pub mod {module};\n"));
    }
    if !group.fragment.is_empty() {
        let table = fragment::table(schema_dir, group.fragment)?;
        std::fs::write(out_dir.join("fragment.rs"), fragment::emit(&table)).map_err(|e| e.to_string())?;
        modrs.push_str("pub mod fragment;\n");
    }
    std::fs::write(out_dir.join("mod.rs"), modrs).map_err(|e| e.to_string())?;
    Ok(())
}

/// The canonical grammar dump of one root element (see [`dump`]).
pub fn dump_grammar(group: &Group, schema_dir: &Path, ns: &str, root: &str) -> Result<String, String> {
    let world = World::load(schema_dir, group.files)?;
    let model = model::Model::new(&world, group.modules)?;
    let mut roots: Vec<QName> = world.global_elements(ns).iter().map(|e| e.name.clone()).collect();
    roots.sort_by(|a, b| (&a.local, &a.ns).cmp(&(&b.local, &b.ns)));
    dump::dump(&model, &QName::new(ns, root), &roots)
}

/// `(namespace, schema file, root element)` of every message (`...Req` / `...Res` element)
/// of the group, for comparing grammars with another implementation.
pub fn message_roots(group: &Group, schema_dir: &Path) -> Result<Vec<(String, String, String)>, String> {
    let world = World::load(schema_dir, group.files)?;
    let mut out = Vec::new();
    for (ns, _) in group.modules {
        let schema = world.schema(ns)?;
        for e in &schema.elements {
            let is_message = e.name.local.ends_with("Req") || e.name.local.ends_with("Res");
            if is_message && e.ty.is_some() {
                out.push((ns.to_string(), schema.file.clone(), e.name.local.clone()));
            }
        }
    }
    Ok(out)
}
