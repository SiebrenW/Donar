//! `exi-gen`: reads the ISO 15118 XSDs and writes `no_std`, allocation-free Rust codecs for
//! their schema-informed EXI representation.
//!
//! The grammar rules (event-code layout, datatype representations, string table) were
//! established against EXIficient and are checked by `cargo xtask grammars` (a diff of the
//! derived grammar with EXIficient's) and by the byte-exact vector tests of the generated
//! crates.

pub mod dump;
pub mod emit;
pub mod fragment;
pub mod model;
pub mod names;
pub mod xsd;

use std::path::Path;

use xsd::{QName, World};

/// A set of schema files that is compiled into one crate: each namespace becomes a module.
pub struct Group {
    pub name: &'static str,
    /// Directory of the schema files below `data/schemas`.
    pub dir: &'static str,
    pub files: &'static [&'static str],
    /// `(namespace, Rust module name)`.
    pub modules: &'static [(&'static str, &'static str)],
    /// Schema files whose element declarations form the fragment grammar (the entry schema and
    /// what it imports), if the group's messages are signed in fragments.
    pub fragment: &'static [&'static str],
    /// `(namespace, element)` of the document root when the messages are parts of one element
    /// (`V2G_Message`) instead of each being a root.
    pub document: Option<(&'static str, &'static str)>,
    /// False when the EXI stream has `valuePartitionCapacity` 0 (DIN SPEC 70121).
    pub value_table: bool,
}

