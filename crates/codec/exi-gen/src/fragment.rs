//! The schema-informed *fragment* grammar of the CommonMessages schema, which ISO 15118-20
//! uses for the parts of a message that are signed (V2G20-1449, canonical EXI): a stream of
//! one element, whose start event is chosen among all element declarations of the schema and
//! its imports (global and local, unique qualified names, sorted by local name, then
//! namespace), followed by the end of the document. This module finds the code of the elements
//! that carry an `Id` (the ones a signature references) and writes them as constants.

use std::collections::BTreeSet;
use std::fmt::Write;
use std::path::Path;

use crate::names;
use crate::xsd::{QName, World, XMLDSIG};

pub struct Table {
    /// Every element declaration, in event-code order.
    pub elements: Vec<QName>,
    /// Elements whose type has an `Id` attribute: `(element, type)`.
    pub signable: Vec<(QName, QName)>,
}

fn resolve(node: roxmltree::Node, value: &str, target_ns: &str) -> QName {
    match value.split_once(':') {
        Some((prefix, local)) => QName::new(node.lookup_namespace_uri(Some(prefix)).unwrap_or(""), local),
        None => QName::new(node.lookup_namespace_uri(None).unwrap_or(target_ns), value),
    }
}

fn has_id(world: &World, ty: &QName) -> bool {
    match world.complex(ty) {
        Some(def) => def.attributes.iter().any(|a| a.name == "Id") || def.base.as_ref().is_some_and(|b| has_id(world, b)),
        None => false,
    }
}

/// `files` are the entry schema and the schemas it imports (the files of the group that the
/// entry schema reaches).
pub fn table(dir: &Path, files: &[&str]) -> Result<Table, String> {
    let world = World::load(dir, files)?;
    let mut elements = BTreeSet::new();
    let mut signable = Vec::new();
    for file in files {
        let text = std::fs::read_to_string(dir.join(file)).map_err(|e| format!("{file}: {e}"))?;
        let options = roxmltree::ParsingOptions { allow_dtd: true, ..Default::default() };
        let doc = roxmltree::Document::parse_with_options(&text, options).map_err(|e| format!("{file}: {e}"))?;
        let root = doc.root_element();
        let target = root.attribute("targetNamespace").unwrap_or("").to_string();
        let qualified = root.attribute("elementFormDefault") == Some("qualified");
        for node in root.descendants().filter(|n| n.is_element() && n.tag_name().name() == "element") {
            let Some(name) = node.attribute("name") else { continue };
            let global = node.parent().is_some_and(|p| p == root);
            let form_qualified = match node.attribute("form") {
                Some(f) => f == "qualified",
                None => qualified,
            };
            let ns = if global || form_qualified { target.clone() } else { String::new() };
            let q = QName::new(&ns, name);
            elements.insert((q.local.clone(), q.ns.clone()));
            if target != XMLDSIG
                && let Some(ty) = node.attribute("type")
            {
                let ty = resolve(node, ty, &target);
                if has_id(&world, &ty) {
                    signable.push((q, ty));
                }
            }
        }
    }
    let elements: Vec<QName> = elements.into_iter().map(|(local, ns)| QName::new(&ns, &local)).collect();
    signable.sort_by(|a, b| (&a.0.local, &a.0.ns).cmp(&(&b.0.local, &b.0.ns)));
    signable.dedup_by(|a, b| a.0 == b.0);
    Ok(Table { elements, signable })
}

/// The Rust source of the `fragment` module.
pub fn emit(t: &Table) -> String {
    let n = t.elements.len() as u32;
    let mut s = String::new();
    s.push_str("// @generated by exi-gen; do not edit.\n//! Codes of the start events of the schema-informed fragment grammar of the\n//! CommonMessages schema (see `exi-gen`'s `fragment` module): the elements that carry an `Id`.\n\n");
    let _ = writeln!(s, "/// Element declarations of the schema and its imports.\npub const ELEMENTS: u32 = {n};");
    let _ = writeln!(s, "/// The end-of-document event after the element.\npub const END: u32 = {};", n + 1);
    let _ = writeln!(s, "/// Bits of every event code of the fragment content.\npub const CODE_BITS: u32 = {};", exi::layout::ceil_log2(u64::from(n) + 3));
    for (element, ty) in &t.signable {
        let code = t.elements.iter().position(|e| e == element).expect("signable elements are elements");
        let name: String = names::words(&element.local).iter().map(|w| w.to_uppercase()).collect::<Vec<_>>().join("_").replace("PN_C", "PNC");
        let _ = writeln!(s, "/// `{}` (type `{}`).\npub const {name}: u32 = {code};", element.local, ty.local);
    }
    // What the signature itself is computed over.
    let info = t.elements.iter().position(|e| e.ns == XMLDSIG && e.local == "SignedInfo").expect("xmldsig is in the table");
    let _ = writeln!(s, "/// `ds:SignedInfo`, the element a signature value is computed over.\npub const SIGNED_INFO: u32 = {info};");
    s
}
